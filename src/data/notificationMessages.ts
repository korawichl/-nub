/**
 * Returns a random notification message appropriate for the given timeslot.
 * If slot is 'morning', picks randomly from morning + general pool.
 * If slot is 'noon', picks randomly from noon + general pool.
 * If slot is 'evening', picks randomly from evening + general pool.
 * If 'any', picks from the entire 50-message catalog.
 */
export function getRandomNotificationMessage(
  slot: 'morning' | 'noon' | 'evening' | 'any' = 'any'
): NotificationMessageItem {
  let candidates: NotificationMessageItem[];

  if (slot === 'any') {
    candidates = GENZ_NOTIFICATION_MESSAGES;
  } else {
    candidates = GENZ_NOTIFICATION_MESSAGES.filter(
      (m) => m.slot === slot || m.slot === 'general'
    );
  }

  if (candidates.length === 0) {
    candidates = GENZ_NOTIFICATION_MESSAGES;
  }

  const randomIndex = Math.floor(Math.random() * candidates.length);
  return candidates[randomIndex];
}

/**
 * Determines current target time slot based on Bangkok hour:
 * 06:00 - 10:59 -> 'morning' (08:00 slot)
 * 11:00 - 15:59 -> 'noon' (12:00 slot)
 * 16:00 - 21:59 -> 'evening' (17:00 slot)
 * otherwise -> 'any'
 */
export function getCurrentSlotByTime(): 'morning' | 'noon' | 'evening' | 'any' {
  const now = new Date();
  // Get Bangkok hour (UTC+7)
  const bangkokHour = (now.getUTCHours() + 7) % 24;

  if (bangkokHour >= 6 && bangkokHour < 11) {
    return 'morning';
  }
  if (bangkokHour >= 11 && bangkokHour < 16) {
    return 'noon';
  }
  if (bangkokHour >= 16 && bangkokHour < 22) {
    return 'evening';
  }
  return 'any';
}
