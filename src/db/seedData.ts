import type { FoodCatalogItem, NutritionGoals, UserProfile, AppSettings } from '../types';
import { BANGKOK_TIMEZONE } from '../utils/date';
import {
  calculateBMR,
  calculateCalorieTarget,
  calculateMacros,
  calculateTDEE,
  ACTIVITY_FACTORS,
} from '../utils/nutritionCalculator';

export const DEFAULT_PROFILE_ID = 'default_profile';
export const DEFAULT_GOALS_ID = 'default_goals';
export const DEFAULT_SETTINGS_ID = 'default_settings';

export function createInitialProfile(): UserProfile {
  return {
    id: DEFAULT_PROFILE_ID,
    age: 18,
    sex: 'male',
    heightCm: 180,
    initialWeightKg: 88,
    targetWeightKg: 80,
    goal: 'fat_loss',
    activityLevel: 'high',
    training: 'swimming and strength training',
    platform: 'PWA',
    storage: 'local device only',
    budget: 'free-first',
    targetDate: undefined,
    updatedAt: new Date().toISOString(),
  };
}

export function createInitialGoals(): NutritionGoals {
  const bmr = calculateBMR({ weightKg: 88, heightCm: 180, age: 18, sex: 'male' }); // 1920
  const activityFactor = ACTIVITY_FACTORS.high; // 1.725
  const estimatedTdee = calculateTDEE(bmr, activityFactor); // 3312
  const calorieTarget = calculateCalorieTarget(estimatedTdee, { customTarget: 2900 }); // 2900
  const macros = calculateMacros({
    calorieTarget,
    proteinGrams: 170,
    fatGrams: 85,
  }); // carbsGrams = 363.75

  return {
    id: DEFAULT_GOALS_ID,
    bmr,
    activityFactor,
    estimatedTdee,
    calorieTarget,
    proteinTargetG: macros.proteinGrams,
    fatTargetG: macros.fatGrams,
    carbsTargetG: macros.carbsGrams,
    waterTargetMl: 3000,
    autoCalculateMacros: true,
    updatedAt: new Date().toISOString(),
  };
}

export function createInitialSettings(): AppSettings {
  return {
    id: DEFAULT_SETTINGS_ID,
    theme: 'dark',
    timezone: BANGKOK_TIMEZONE,
    aiProviderId: 'free_builtin',
    updatedAt: new Date().toISOString(),
  };
}

